"""Summarize D1 unit results into derisk/results/D1_summary.md (+ .json). Pilot numbers; nothing frozen."""
import glob, json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTROLS = {"bv20", "bv20r3"}
FAM = {"sup": "supremacy", "aqft": "aqft", "qaoa": "qaoa", "adder": "adder", "bv": "bv"}


def fam(iid):
    for k, v in FAM.items():
        if iid.startswith(k):
            return v


def main():
    recs = [json.loads(Path(f).read_text()) for f in sorted(glob.glob(str(ROOT / "derisk/results/D1/*.json")))]
    cells, lines = [], []
    lines.append("| instance | noise | S | raw support (mean, per subcircuit) | merged ψ ratio | query | φ ratio (all factors) | max intermediate ratio | answer ratio |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for r in recs:
        raw = ", ".join(f"{v['mean']:.2f}" for v in r["raw"].values())
        mr = sum(v["nnz"] for v in r["merged"].values()) / sum(v["nnz"] / v["ratio"] for v in r["merged"].values() if v["ratio"] > 0)
        for k, q in r["queries"].items():
            phis = q["phi"].values()
            num = sum(p["nnz"] for p in phis); den = sum(p["nnz"] / p["ratio"] for p in phis if p["ratio"] > 0)
            phi_ratio = num / den if den else 0.0
            inter = q.get("intermediates")
            if isinstance(inter, list) and inter:
                ir = max(x["ratio"] for x in inter); ans = q["answer"]["ratio"]
            else:
                ir, ans = None, None
            cells.append({"id": r["id"], "family": fam(r["id"]), "noise": r["noise"], "S": r["S"], "query": k,
                          "phi_ratio": phi_ratio, "max_inter_ratio": ir, "answer_ratio": ans,
                          "merged_ratio": mr, "control": r["id"] in CONTROLS,
                          "max_width": max(v["width"] for v in r["raw"].values())})
            lines.append(f"| {r['id']} | {r['noise']} | {r['S']} | {raw} | {mr:.3g} | |A|={k} | {phi_ratio:.3g} | "
                         f"{'DNF' if ir is None else f'{ir:.3g}'} | {'—' if ans is None else f'{ans:.3g}'} |")
    nc = [c for c in cells if not c["control"]]
    below10 = [c for c in nc if c["phi_ratio"] < 0.10]
    above50 = [c for c in nc if c["phi_ratio"] >= 0.50]
    # K-SPARSE first condition: on EVERY family at EVERY S, factors after pushdown >= 50%
    by_fs = defaultdict(list)
    for c in nc:
        by_fs[(c["family"], c["S"])].append(c["phi_ratio"])
    ksparse_support = all(min(v) >= 0.5 for v in by_fs.values())
    # expectation: wide queries (|A| >= 20) below 10% for widths >= 15 and S <= 1e4, on every family
    exp_cells = [c for c in nc if c["query"] != "10" and c["S"] <= 10000 and c["max_width"] >= 15]
    summary = {"cells": len(cells), "non_control_cells": len(nc), "share_below_10pct": len(below10) / len(nc),
               "share_at_or_above_50pct": len(above50) / len(nc),
               "ksparse_support_condition": ksparse_support,
               "expectation_cells": len(exp_cells),
               "expectation_cells_below_10pct": sum(c["phi_ratio"] < 0.1 for c in exp_cells),
               "narrow_marg10_dense_share(>50%)": sum(c["phi_ratio"] > 0.5 for c in nc if c["query"] == "10") /
               max(1, sum(1 for c in nc if c["query"] == "10")),
               "by_family_S_min_phi_ratio": {f"{k[0]}|S={k[1]}": min(v) for k, v in sorted(by_fs.items())},
               "by_family_S_max_phi_ratio": {f"{k[0]}|S={k[1]}": max(v) for k, v in sorted(by_fs.items())}}
    (ROOT / "derisk/results/D1_summary.json").write_text(json.dumps({"summary": summary, "cells": cells}, indent=1))
    (ROOT / "derisk/results/D1_summary.md").write_text(encoding="utf-8", data=
        "# D1 support measurement — pilot summary (generated by derisk/d1_summary.py)\n\n"
        "Ratios are stored entries / dense shape. φ ratio pools all pushed-down factors of the instance "
        "(Σ nnz / Σ 4^{|δ(j)|}·2^{|A∩O_j|}). Intermediates: default-rule plan run sparse (row cap 6e7 → DNF).\n\n"
        "```\n" + json.dumps(summary, indent=1) + "\n```\n\n" + "\n".join(lines) + "\n")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
